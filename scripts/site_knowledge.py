"""Extract only published page bodies and manifest-listed announcements for chat."""

import json
import re
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


class PageText(HTMLParser):
    def __init__(self, main_only=True):
        super().__init__(convert_charrefs=True)
        self.main_only = main_only
        self.in_main = False
        self.skip = 0
        self.parts = []
        self.title = []
        self.in_title = False

    def handle_starttag(self, tag, attrs):
        if tag == "title":
            self.in_title = True
        if tag == "main":
            self.in_main = True
        if tag in {"script", "style", "nav", "form"}:
            self.skip += 1
        if tag in {"p", "div", "section", "li", "br", "tr", "h1", "h2", "h3", "h4", "pre"}:
            self.parts.append("\n")
        if tag == "img" and (self.in_main or not self.main_only) and not self.skip:
            self.parts.append(dict(attrs).get("alt", "") + " ")

    def handle_endtag(self, tag):
        if tag == "title":
            self.in_title = False
        if tag == "main":
            self.in_main = False
        if tag in {"script", "style", "nav", "form"}:
            self.skip = max(0, self.skip - 1)
        if tag in {"p", "div", "section", "li", "tr", "h1", "h2", "h3", "h4", "pre"}:
            self.parts.append("\n")

    def handle_data(self, data):
        if self.in_title:
            self.title.append(data)
        if (self.in_main or not self.main_only) and not self.skip:
            self.parts.append(data)

    def text(self):
        return "\n".join(line for part in "".join(self.parts).splitlines()
                         if (line := re.sub(r"\s+", " ", part).strip()))


def documents(root=ROOT):
    docs = []
    for path in sorted(root.glob("*.html")):
        parser = PageText()
        parser.feed(path.read_text())
        text = parser.text()
        if not text:
            raise ValueError(f"No main content extracted from {path.name}")
        docs.append(dict(title="".join(parser.title).split(" | ")[0],
                         url="/" if path.name == "index.html" else "/" + path.name,
                         date=None, text=text))
    manifest = json.loads((root / "announcements/manifest.json").read_text())
    for entry in sorted(manifest, key=lambda item: item["date"], reverse=True):
        filename = entry["file"]
        if Path(filename).name != filename or Path(filename).suffix not in {".md", ".html"}:
            raise ValueError(f"Invalid announcement: {filename}")
        text = (root / "announcements" / filename).read_text().strip()
        if filename.endswith(".html"):
            parser = PageText(main_only=False)
            parser.feed(text)
            text = parser.text()
        docs.append(dict(title=entry["title"], date=entry["date"], text=text,
                         url="/#announcement-" + Path(filename).stem))
    return docs


def generate(root=ROOT):
    docs = documents(root)
    source = "// Generated by scripts/site_knowledge.py; edit the public source documents instead.\n"
    source += "export const documents = " + json.dumps(docs, ensure_ascii=True, indent=2) + ";\n"
    (root / "worker/site-knowledge.mjs").write_text(source)
    return docs


if __name__ == "__main__":
    docs = generate()
    print(f"Indexed {len(docs)} public documents ({sum(len(doc['text']) for doc in docs)} characters)")
